def _sim_to_tw(text: str) -> str:
    out = []
    i = 0
    while i < len(text):
        # 处理双字词
        if i + 1 < len(text) and text[i:i + 2] in SIM2TW:
            out.append(SIM2TW[text[i:i + 2]])
            i += 2
            continue
        ch = text[i]
        out.append(SIM2TW.get(ch, ch))
        i += 1
    return "".join(out)


