    if lang == "zh-CN" or zh not in TRANSLATIONS:
        if lang == "zh-TW":
            return _sim_to_tw(zh)
        return zh
    tw, en = TRANSLATIONS[zh]
    if lang == "zh-TW":
        return tw
    if lang == "en":
        return en
    return zh
